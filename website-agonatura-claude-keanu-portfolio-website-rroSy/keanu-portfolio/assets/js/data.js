// Helpers
window.KK = {
  all: () => window.MEDIA_LIBRARY.filter(m => m.status === "published"),
  byCategory: (cat) => window.KK.all().filter(m => m.category === cat),
  byId: (id) => window.MEDIA_LIBRARY.find(m => m.id === id),
  featured: () => window.KK.all().find(m => m.featured) || window.KK.all()[0],
  newest: (n = 8) =>
    [...window.KK.all()]
      .sort((a, b) => new Date(b.createdAt) - new Date(a.createdAt))
      .slice(0, n),
  favorites: (n = 8) => window.KK.all().filter(m => m.featured).slice(0, n),
};
